const LOCALES = ['ar', 'en', 'es', 'hi', 'id', 'nl', 'pt', 'th', 'tr', 'vi', 'zh_CN']

function messagesFor(locale) {
  const source = locale === 'zh_CN' ? ZH : EN
  const out = {}
  for (const [key, message] of Object.entries(source)) {
    out[key] = { message, description: key }
  }
  return out
}

for (const locale of LOCALES) {
  const file = path.join(localesDir, locale, 'messages.json')
  const current = JSON.parse(fs.readFileSync(file, 'utf8'))
  const extra = messagesFor(locale)
  const merged = { ...current, ...extra }
  fs.writeFileSync(file, `${JSON.stringify(merged, null, 2)}\n`)
  console.log(`updated ${locale} (+${Object.keys(extra).length} ai/cmd keys)`)
}
